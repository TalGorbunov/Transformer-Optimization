def _write_csv(path, rows, cols):
    with open(path, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=cols)
        w.writeheader()
        w.writerows(rows)


def flip_tables(N, alpha=0.72, n_pairs=40, seed=0, qtype="steps_in_room", arm="plain", layers=(20,), golds=(1, 2, 3),
                gamma=None, gamma_C=2.0, amp=20.0, sigma=0.2, qid_prefix="q"):
    """pairs/controls/logits rows for one N; median dnorm = amp * N^-alpha (* (gold+C)^-gamma if gamma) with
    lognormal noise. Each pair = one evid flip; controls = replay (0) / ctrl / perm rows."""
    rng = np.random.RandomState(seed + N)
    pairs, controls, logits = [], [], []
    for i in range(n_pairs):
        gold = golds[i % len(golds)]
        qid = f"{qid_prefix}_{qtype}_N{N}_{i:04d}"
        flip_t = int(rng.randint(0, N))
        for layer in layers:
            med = amp * N ** (-alpha) * ((gold + gamma_C) ** (-gamma) if gamma is not None else 1.0)
            d = med * np.exp(sigma * rng.randn())
            pairs.append(dict(qid=qid, qtype=qtype, n_frames=N, gold=gold, flip_t=flip_t, flip_kind="evid", arm=arm, layer=layer,
                              locus="final", dnorm=f"{d:.6f}", base_norm="100"))
            if i < 10:
                for kind, v in (("replay", 0.0), ("ctrl", 0.05 * np.exp(0.1 * rng.randn())), ("perm", 0.1)):
                    controls.append(dict(qid=qid, qtype=qtype, n_frames=N, kind=kind, arm=arm, layer=layer, locus="final",
                                         dnorm=f"{v:.6f}", base_norm="100"))
        mb = 2.0 - 0.02 * N + 0.3 * rng.randn()
        pred_base = gold if mb > 0 else gold + 1
        logits.append(dict(qid=qid, qtype=qtype, n_frames=N, gold=gold, arm=arm, flip_kind="evid", margin_base=f"{mb:.4f}",
                           margin_flip=f"{mb - 1.0:.4f}", pred_base=pred_base, pred_flip=pred_base + 1, dlogit="1.0"))
        if i < 10:
            logits.append(dict(qid=qid, qtype=qtype, n_frames=N, gold=gold, arm=arm, flip_kind="ctrl", margin_base=f"{mb:.4f}",
                               margin_flip=f"{mb + 0.05:.4f}", pred_base=pred_base, pred_flip=pred_base, dlogit="0.05"))
    return pairs, controls, logits


PAIR_COLS = "qid,qtype,n_frames,gold,flip_t,flip_kind,arm,layer,locus,dnorm,base_norm".split(",")
CTRL_COLS = "qid,qtype,n_frames,kind,arm,layer,locus,dnorm,base_norm".split(",")
LOGIT_COLS = "qid,qtype,n_frames,gold,arm,flip_kind,margin_base,margin_flip,pred_base,pred_flip,dlogit".split(",")
MASS_COLS = "qid,qtype,N,k,layer,head,evid_mass,nonevid_mass,other_mass".split(",")
BLOCK_COLS = "qid,qtype,N,k,layer,head,block,is_evid,mass".split(",")


def photo_tables(N, ks=(2, 4, 8), s=0.3, C=8.0, noise=0.01, n_samples=20, n_heads=4, layer=20, seed=0, qtype="steps_in_room"):
    """mass/block_mass rows generated by the share law (+ gaussian noise on the head-level evid mass)."""
    rng = np.random.RandomState(seed + N)
    mass, blocks, auc = [], [], {}
    for k in ks:
        m = float(law((np.array([N], float), np.array([k], float)), s, C)[0])
        for i in range(n_samples):
            qid = f"{qtype}_N{N}_K{k}_{i:04d}"
            evid_blocks = set(rng.choice(N, k, replace=False).tolist())
            for h in range(n_heads):
                e = min(max(m + noise * rng.randn(), 1e-4), 0.999)
                ne = (1 - e) * 0.8
                mass.append(dict(qid=qid, qtype=qtype, N=N, k=k, layer=layer, head=h, evid_mass=f"{e:.6f}",
                                 nonevid_mass=f"{ne:.6f}", other_mass=f"{1 - e - ne:.6f}"))
                for b in range(N):
                    is_e = int(b in evid_blocks)
                    mb = e / k if is_e else ne / max(N - k, 1)
                    blocks.append(dict(qid=qid, qtype=qtype, N=N, k=k, layer=layer, head=h, block=b, is_evid=is_e, mass=f"{mb:.6f}"))
    for h in range(n_heads):
        auc[f"L{layer}_h{h}"] = 0.99 if h == 0 else 0.7 + 0.05 * h
    auc["L24_h20"] = 0.999
    return mass, blocks, auc


def write_flip_run(d, N, **kw):
    d = Path(d)
    d.mkdir(parents=True, exist_ok=True)
    pairs, controls, logits = flip_tables(N, **kw)
    _write_csv(d / "pairs.csv", pairs, PAIR_COLS)
    _write_csv(d / "controls.csv", controls, CTRL_COLS)
    _write_csv(d / "logits.csv", logits, LOGIT_COLS)
    (d / "config.json").write_text(json.dumps({"config": f"seq_len_{N}", "split": "test", "qtypes": [kw.get("qtype", "steps_in_room")],
                                               "arms": [kw.get("arm", "plain")], "attn_sharpen": 0, "sharpen_from_layer": 12,
                                               "attn_logn_sref": 0, "adapter": None}))


def write_photo_run(d, N, arm="qfirst", tau=0, **kw):
    d = Path(d)
    d.mkdir(parents=True, exist_ok=True)
    mass, blocks, auc = photo_tables(N, **kw)
    _write_csv(d / "mass.csv", mass, MASS_COLS)
    _write_csv(d / "block_mass.csv", blocks, BLOCK_COLS)
    (d / "auc.json").write_text(json.dumps(auc))
    (d / "config.json").write_text(json.dumps({"config": f"seq_len_{N}", "arm": arm, "qtypes": [kw.get("qtype", "steps_in_room")],
                                               "attn_sharpen": tau, "sharpen_from_layer": 12, "attn_logn_sref": 0, "adapter": None}))


def _tables(rows, cols, N, cfg=None):
    with tempfile.TemporaryDirectory() as td:
        p = Path(td) / "t.csv"
        _write_csv(p, rows, cols)
        return annotate(read_table(p), cfg or {}, f"run_N{N}")


