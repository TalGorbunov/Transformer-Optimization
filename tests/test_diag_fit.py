def test_alpha_recovers_exponent():
    P, Cc = [], []
    for N in NS:
        pairs, controls, _ = flip_tables(N, alpha=0.72, n_pairs=60)
        P.append(_tables(pairs, PAIR_COLS, N))
        Cc.append(_tables(controls, CTRL_COLS, N))
    res = fit_alpha(concat(P), concat(Cc), n_boot=500)
    assert len(res["cells"]) == 1, res["cells"]
    c = res["cells"][0]
    assert (c["qtype"], c["arm"], c["cond"], c["model"], c["layer"], c["locus"]) == ("steps_in_room", "plain", "base", "frozen", 20, "final")
    assert abs(c["alpha"] - 0.72) < 0.03, c["alpha"]
    assert c["ci"][0] < 0.72 < c["ci"][1] and c["r2"] > 0.95, (c["ci"], c["r2"])
    assert c["N"] == list(NS) and c["n"] == [60] * 5
    assert c["floors"]["replay"]["max"] == 0.0 and 0.03 < c["floors"]["ctrl"]["median"] < 0.07 and c["floors"]["perm"]["per_N"][8] == 0.1
    assert set(c["by_gold"]) == {"1", "2", "3"} and all(abs(f["alpha"] - 0.72) < 0.1 for f in c["by_gold"].values())
    assert set(c["by_position"]) == {"first", "middle", "last"}
    assert "pooled alpha 0.7" in c["pooled_vs_stratified"]


